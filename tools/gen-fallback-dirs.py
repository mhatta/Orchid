#!/usr/bin/env python3
"""Regenerate src/main/java/com/subgraph/orchid/directory/FallbackDirectoryList.java.

Usage:
    tools/gen-fallback-dirs.py FALLBACK_LIST > \\
        src/main/java/com/subgraph/orchid/directory/FallbackDirectoryList.java

FALLBACK_LIST is either Tor's src/app/config/fallback_dirs.inc (preferred,
from a current Tor release) or Arti's tor-dircommon data/fallback_dirs.rs,
which is generated from the same source.  Only the IPv4 address of each
fallback is kept because Orchid connects over IPv4 only.
"""
import re
import sys

ENTRY_LINE = '        "%s %s %s",'


def parse_tor_inc(src):
    # "1.2.3.4 orport=443 id=<40 hex>"  [" ipv6=[...]:443"]  /* nickname=... */
    pattern = re.compile(
        r'"(\d{1,3}(?:\.\d{1,3}){3}) orport=(\d{1,5}) id=([0-9A-Fa-f]{40})"'
        r'(?:\s*"[^"]*")*\s*/\*\s*nickname=(\S*)\s*\*/')
    for m in pattern.finditer(src):
        ip, port, ident, nick = m.groups()
        yield '%s:%s' % (ip, port), ident.upper(), nick


def parse_arti_rs(src):
    pattern = re.compile(
        r'// Nickname: (\S+)\s*\n\s*fallback\(\s*"([0-9A-Fa-f]{40})",\s*"[^"]*",\s*&\[(.*?)\]', re.S)
    for m in pattern.finditer(src):
        nick, ident, addrs = m.groups()
        v4 = [a for a in re.findall(r'"([^"]+)"', addrs)
              if re.fullmatch(r'\d{1,3}(?:\.\d{1,3}){3}:\d{1,5}', a)]
        if v4:
            yield v4[0], ident.upper(), nick


def valid(addr, ident, nick):
    ip, port = addr.split(':')
    return (all(0 <= int(o) <= 255 for o in ip.split('.'))
            and 0 < int(port) < 65536
            and re.fullmatch(r'[A-Za-z0-9]{1,19}', nick or 'Unnamed'))


def main():
    src = open(sys.argv[1], encoding='utf-8').read()
    m = re.search(r'Generated on:\s*(.+)', src)
    generated = m.group(1).strip() if m else 'unknown date'
    parser = parse_arti_rs if 'fallback(' in src else parse_tor_inc
    entries, seen = [], set()
    for addr, ident, nick in parser(src):
        nick = nick or 'Unnamed'
        if ident in seen or not valid(addr, ident, nick):
            continue
        seen.add(ident)
        entries.append((addr, ident, nick))
    if len(entries) < 50:
        sys.exit('only %d fallbacks parsed from %s; refusing to write a short list'
                 % (len(entries), sys.argv[1]))
    print('%d fallback directories, list generated on %s' % (len(entries), generated),
          file=sys.stderr)

    out = [
        'package com.subgraph.orchid.directory;',
        '',
        '/**',
        ' * Fallback directory mirrors: long-running relays that clients contact to',
        ' * bootstrap instead of the directory authorities (dir-spec, "Fallback',
        ' * directories").  Each entry is "address:orport identity nickname".',
        ' *',
        ' * Generated by tools/gen-fallback-dirs.py from the fallback list that Tor',
        ' * ships in src/app/config/fallback_dirs.inc (list generated on',
        ' * %s).' % generated,
        ' * Only IPv4 addresses are kept because Orchid connects over IPv4 only.',
        ' * Regenerate it from a current Tor release from time to time: a fallback',
        ' * that has gone away only costs a connection attempt, but the list becomes',
        ' * useless once most of its relays have disappeared.',
        ' */',
        'final class FallbackDirectoryList {',
        '    private FallbackDirectoryList() {}',
        '',
        '    static final String[] FALLBACK_DIRECTORIES = {',
    ]
    out += [ENTRY_LINE % e for e in entries]
    out += ['    };', '}']
    print('\n'.join(out))


if __name__ == '__main__':
    main()
